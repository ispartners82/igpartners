/**
 * 병원 객체로부터 매칭되는 8개국어 번역 엔트리를 조회하는 함수
 * @param {Object} clinic - 병원 데이터 객체
 * @returns {Object|null} 8개국어 번역 객체 또는 null
 */
export function findClinic8LangTranslationEntry(clinic) {
  if (!clinic) return null;
  const candidates = [
    clinic.id,
    clinic.name,
    clinic.name ? clinic.name.trim() : "",
    clinic.englishName,
    clinic.englishName ? clinic.englishName.trim() : ""
  ].filter(Boolean);

  for (const key of candidates) {
    if (CLINIC_8LANG_TRANSLATIONS[key]) {
      return CLINIC_8LANG_TRANSLATIONS[key];
    }
    const mappedKey = CLINIC_KEY_ALIASES[key];
    if (mappedKey && CLINIC_8LANG_TRANSLATIONS[mappedKey]) {
      return CLINIC_8LANG_TRANSLATIONS[mappedKey];
    }
  }
  return null;
}

/**
 * 병원 데이터 객체에서 비어 있는 8개국어(ja, zh, th, lo, ne, id, si, bn) 필드만 안전하게 채워 넣고,
 * Firestore 업데이트가 필요한 필드 객체를 함께 반환하는 함수
 * @param {Object} clinic - 원본 병원 데이터 객체 (직접 보강됨)
 * @returns {Object} Firestore에 저장해야 할 누락 필드 업데이트 패치 객체 (변경 없으면 빈 객체)
 */
export function enrichClinicWithMissing8Langs(clinic) {
  const patch = {};
  if (!clinic) return patch;

  const translationMap = findClinic8LangTranslationEntry(clinic);
  if (!translationMap) return patch;

  TARGET_EMPTY_8_LANGS.forEach((langCode) => {
    const langData = translationMap[langCode];
    if (!langData) return;

    const nameField = `name_${langCode}`;
    const deptsField = `depts_${langCode}`;
    const addressField = `address_${langCode}`;
    const descField = `desc_${langCode}`;

    // 1. 병원명: 비어 있을 때만 채움
    if (!clinic[nameField] || String(clinic[nameField]).trim() === "") {
      clinic[nameField] = langData.name;
      patch[nameField] = langData.name;
    }

    // 2. 진료과목 배열: 비어 있을 때만 채움
    if (!Array.isArray(clinic[deptsField]) || clinic[deptsField].length === 0) {
      clinic[deptsField] = [...langData.depts];
      patch[deptsField] = [...langData.depts];
    }

    // 3. 병원 주소: 비어 있을 때만 채움
    if (!clinic[addressField] || String(clinic[addressField]).trim() === "") {
      clinic[addressField] = langData.address;
      patch[addressField] = langData.address;
    }

    // 4. 병원 설명: 비어 있을 때만 채움
    if (!clinic[descField] || String(clinic[descField]).trim() === "") {
      clinic[descField] = langData.desc;
      patch[descField] = langData.desc;
    }
  });

  return patch;
}
